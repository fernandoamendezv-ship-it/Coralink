export function extractImageName(url: string): string {
  try {
    const parts = url.split('/');
    const last = parts[parts.length - 1];
    return decodeURIComponent(last.replace(/\.[^/.]+$/, '').replace(/[-_]/g, ' '));
  } catch (_) {
    return 'Foto de producto';
  }
}
